import { createHash, createPrivateKey, randomBytes, randomInt, timingSafeEqual } from 'node:crypto';
import { createRemoteJWKSet, customFetch, jwtVerify, SignJWT } from 'jose';

const ROOT = '/api/battle/auth';
const LIFETIME = 10 * 60_000;
const TOKEN_TIMEOUT = 8_000;
const MAX_BODY = 16_384;
const PROVIDERS = {
  kakao: {
    authorize: 'https://kauth.kakao.com/oauth/authorize', token: 'https://kauth.kakao.com/oauth/token',
    userinfo: 'https://kapi.kakao.com/v2/user/me', pkce: true,
  },
  naver: {
    authorize: 'https://nid.naver.com/oauth2.0/authorize', token: 'https://nid.naver.com/oauth2.0/token',
    userinfo: 'https://openapi.naver.com/v1/nid/me',
  },
  google: {
    authorize: 'https://accounts.google.com/o/oauth2/v2/auth', token: 'https://oauth2.googleapis.com/token',
    jwks: 'https://www.googleapis.com/oauth2/v3/certs', issuer: ['https://accounts.google.com', 'accounts.google.com'],
    pkce: true,
  },
  apple: {
    authorize: 'https://appleid.apple.com/auth/authorize', token: 'https://appleid.apple.com/auth/token',
    jwks: 'https://appleid.apple.com/auth/keys', issuer: 'https://appleid.apple.com',
  },
};

function opaque() { return randomBytes(32).toString('base64url'); }
function digest(value) { return createHash('sha256').update(value).digest('base64url'); }
function same(a, b) {
  return typeof a === 'string' && typeof b === 'string' &&
    timingSafeEqual(Buffer.from(digest(a)), Buffer.from(digest(b)));
}

class AuthError extends Error {
  constructor(status, code) { super(code); this.status = status; this.code = code; }
}
const expired = () => new AuthError(410, 'AUTH_FLOW_EXPIRED');
const upstreamFailed = () => new AuthError(502, 'AUTH_PROVIDER_FAILED');

function publicOrigin(input) {
  if (!input) return null;
  try {
    const url = new URL(input);
    const loopback = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
    if (url.username || url.password || url.pathname !== '/' || url.search || url.hash) return null;
    return url.protocol === 'https:' || (loopback && url.protocol === 'http:') ? url.origin : null;
  } catch { return null; }
}

function configuredProviders(env, fetchImpl) {
  const configured = new Map();
  for (const [name, endpoints] of Object.entries(PROVIDERS)) {
    const prefix = 'BATTLE_' + name.toUpperCase() + '_';
    const id = env[prefix + 'CLIENT_ID']?.trim();
    if (!id) continue;
    const provider = { ...endpoints, name, id };
    if (name === 'apple') {
      provider.team = env.BATTLE_APPLE_TEAM_ID?.trim();
      provider.kid = env.BATTLE_APPLE_KEY_ID?.trim();
      if (!provider.team || !provider.kid || !env.BATTLE_APPLE_PRIVATE_KEY) continue;
      try {
        provider.key = createPrivateKey(env.BATTLE_APPLE_PRIVATE_KEY.replace(/\\n/g, '\n'));
        if (provider.key.asymmetricKeyDetails?.namedCurve !== 'prime256v1') continue;
      } catch { continue; }
    } else {
      provider.secret = env[prefix + 'CLIENT_SECRET']?.trim();
      // Kakao apps with "Client Secret" disabled can use just their REST API key.
      if (!provider.secret && name !== 'kakao') continue;
    }
    if (provider.jwks) {
      provider.keySet = createRemoteJWKSet(new URL(provider.jwks), {
        [customFetch]: fetchImpl, timeoutDuration: TOKEN_TIMEOUT,
      });
    }
    configured.set(name, provider);
  }
  return configured;
}

async function parseBody(req, form = false) {
  const mime = String(req.headers['content-type'] || '').split(';')[0].trim().toLowerCase();
  if (mime !== (form ? 'application/x-www-form-urlencoded' : 'application/json')) {
    throw new AuthError(415, 'UNSUPPORTED_CONTENT_TYPE');
  }
  if (Number(req.headers['content-length']) > MAX_BODY) throw new AuthError(413, 'BODY_TOO_LARGE');
  const chunks = [];
  let length = 0;
  for await (const chunk of req) {
    length += chunk.length;
    if (length > MAX_BODY) throw new AuthError(413, 'BODY_TOO_LARGE');
    chunks.push(chunk);
  }
  const raw = Buffer.concat(chunks).toString('utf8');
  if (form) return new URLSearchParams(raw);
  try {
    const body = JSON.parse(raw);
    if (body && typeof body === 'object' && !Array.isArray(body)) return body;
  } catch {}
  throw new AuthError(400, 'INVALID_BODY');
}

function json(res, status, body) {
  res.writeHead(status, { 'Content-Type': 'application/json; charset=utf-8' });
  res.end(JSON.stringify(body));
}

function browserResult(res, success, receipt) {
  const nonce = randomBytes(18).toString('base64');
  const title = success ? '로그인 확인 코드' : '로그인을 마치지 못했습니다';
  const message = success
    ? '볼탱이 대전으로 돌아가세요. 게임에서 코드를 요청하면 아래 숫자 여섯 자리를 입력하세요.'
    : '게임으로 돌아가 로그인 버튼을 다시 선택해 주세요.';
  const code = success ? `<output id="confirmation-code" aria-label="확인 코드">${receipt.confirmationCode}</output>` : '';
  // Receipt fields are generated by this server (base64url handle and six decimal digits).
  const broadcast = success ? `<script nonce="${nonce}">try { const c = new BroadcastChannel('battle-social-confirm-v1'); c.postMessage(${JSON.stringify({ type:'battle-social-confirm', ...receipt })}); c.close(); } catch {}</script>` : '';
  res.writeHead(success ? 200 : 400, {
    'Content-Type': 'text/html; charset=utf-8',
    'Content-Security-Policy': `default-src 'none'; style-src 'nonce-${nonce}'; script-src 'nonce-${nonce}'; frame-ancestors 'none'; base-uri 'none'; form-action 'none'`,
    'X-Frame-Options': 'DENY',
  });
  res.end(`<!doctype html><html lang="ko"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${title} · 볼탱이 대전</title><style nonce="${nonce}">*{box-sizing:border-box}body{margin:0;background:#102944;color:#edf8ff;font:16px/1.6 system-ui,sans-serif;min-height:100vh;display:grid;place-items:center;padding:24px}main{max-width:28rem}h1{font-size:1.6rem}p{color:#cce1ee}output{display:block;color:#ffe399;font:bold 2.6rem monospace;letter-spacing:.2em}</style><main><h1>${title}</h1><p>${message}</p>${code}</main>${broadcast}</html>`);
}

async function upstreamJson(fetchImpl, url, init) {
  const response = await fetchImpl(url, { ...init, redirect: 'error', signal: AbortSignal.timeout(TOKEN_TIMEOUT) });
  if (!response.ok) throw upstreamFailed();
  const data = await response.json();
  if (!data || typeof data !== 'object' || data.error) throw upstreamFailed();
  return data;
}

async function verifiedSubject(provider, flow, code, redirectUri, fetchImpl) {
  const form = new URLSearchParams({ grant_type: 'authorization_code', client_id: provider.id, code, redirect_uri: redirectUri });
  if (provider.name === 'apple') {
    const assertion = await new SignJWT({}).setProtectedHeader({ alg: 'ES256', kid: provider.kid })
      .setIssuer(provider.team).setSubject(provider.id).setAudience('https://appleid.apple.com')
      .setIssuedAt().setExpirationTime('5m').sign(provider.key);
    form.set('client_secret', assertion);
  } else if (provider.secret) form.set('client_secret', provider.secret);
  if (provider.pkce) form.set('code_verifier', flow.verifier);
  if (provider.name === 'naver') form.set('state', flow.state);
  const tokens = await upstreamJson(fetchImpl, provider.token, {
    method: 'POST', headers: { Accept: 'application/json', 'Content-Type': 'application/x-www-form-urlencoded' }, body: form,
  });

  if (provider.keySet) {
    const { payload } = await jwtVerify(tokens.id_token, provider.keySet, {
      algorithms: ['RS256'], issuer: provider.issuer, audience: provider.id,
      requiredClaims: ['sub', 'iat', 'exp', 'nonce'], maxTokenAge: '10m', clockTolerance: 30,
    });
    if (!same(payload.nonce, flow.nonce) || (payload.azp !== undefined && payload.azp !== provider.id) ||
        (Array.isArray(payload.aud) && payload.aud.length > 1 && payload.azp !== provider.id)) throw upstreamFailed();
    if (typeof payload.sub !== 'string' || !payload.sub || payload.sub.length > 255) throw upstreamFailed();
    return payload.sub;
  }

  if (typeof tokens.access_token !== 'string' || !tokens.access_token ||
      (tokens.token_type && String(tokens.token_type).toLowerCase() !== 'bearer')) throw upstreamFailed();
  const profile = await upstreamJson(fetchImpl, provider.userinfo, {
    headers: { Authorization: 'Bearer ' + tokens.access_token, Accept: 'application/json' },
  });
  if (provider.name === 'naver' && profile.resultcode === '00' && typeof profile.response?.id === 'string' &&
      profile.response.id.length > 0 && profile.response.id.length <= 255) return profile.response.id;
  if (provider.name === 'kakao') {
    if (Number.isSafeInteger(profile.id) && profile.id > 0) return String(profile.id);
    if (typeof profile.id === 'string' && /^[1-9]\d{0,19}$/.test(profile.id)) return profile.id;
  }
  throw upstreamFailed();
}

/**
 * The callback browser and the game may be separate user agents (e.g. Android WebView and Chrome).
 * A completed provider login is bound to both: the game holds the claim token, and the browser
 * gets a short receipt. Same-origin tabs can pair silently through BroadcastChannel.
 */
export function createSocialAuth({ store, env = process.env, fetchImpl = fetch, now = Date.now } = {}) {
  const origin = publicOrigin(env.BATTLE_AUTH_ORIGIN);
  const providers = origin ? configuredProviders(env, fetchImpl) : new Map();
  const claims = new Map();
  const states = new Map();
  const tickets = new Map();
  const callback = id => origin + ROOT + '/callback/' + id;
  const cookieName = flow => 'btl_auth_' + flow.id;
  const cookie = (flow, value, age) => `${cookieName(flow)}=${value}; Path=${ROOT}/callback/${flow.provider}; Max-Age=${age}; Secure; HttpOnly; SameSite=${flow.provider === 'apple' ? 'None' : 'Lax'}`;
  let nextSweep = 0;

  function discard(flow) {
    claims.delete(flow.claimHash);
    tickets.delete(flow.ticketHash);
    states.delete(flow.state);
    flow.accountToken = '';
    flow.subject = '';
  }
  function live(flow) {
    if (!flow || flow.expires <= now()) {
      if (flow) discard(flow);
      throw expired();
    }
    return flow;
  }
  function sweep() {
    if (now() < nextSweep) return;
    for (const flow of claims.values()) if (flow.expires <= now()) discard(flow);
    nextSweep = now() + 30_000;
  }

  return async function handleSocialAuth(req, res, requestUrl) {
    const url = requestUrl instanceof URL ? requestUrl : new URL(req.url, 'http://localhost');
    if (!url.pathname.startsWith(ROOT + '/')) return false;
    res.setHeader('Cache-Control', 'no-store');
    res.setHeader('Referrer-Policy', 'no-referrer');
    res.setHeader('X-Content-Type-Options', 'nosniff');
    const route = url.pathname.slice(ROOT.length + 1);
    sweep();
    try {
      if (route === 'providers' && req.method === 'GET') {
        json(res, 200, { providers: [...providers.keys()] });
      } else if (route === 'start' && req.method === 'POST') {
        const body = await parseBody(req);
        const provider = providers.get(body.provider);
        if (!provider) throw new AuthError(503, 'AUTH_PROVIDER_UNAVAILABLE');
        if (claims.size >= 2048) throw new AuthError(429, 'AUTH_BUSY');
        const authorization = req.headers.authorization;
        if (authorization && !/^Bearer [^\s]+$/i.test(authorization)) throw new AuthError(401, 'INVALID_ACCOUNT_TOKEN');
        const accountToken = authorization ? authorization.slice(7) : '';
        if (accountToken) store.authenticateAccount(accountToken);
        const ticket = opaque(), claimToken = opaque();
        const flow = {
          id: opaque(), state: opaque(), provider: provider.name, claimHash: digest(claimToken),
          ticketHash: digest(ticket), verifier: opaque(), nonce: opaque(), cookieHash: '', accountToken,
          nickname: typeof body.nickname === 'string' ? body.nickname : '', expires: now() + LIFETIME,
          status: 'pending', attempts: 0,
        };
        claims.set(flow.claimHash, flow);
        states.set(flow.state, flow);
        tickets.set(flow.ticketHash, flow);
        json(res, 200, { authorizeUrl: origin + ROOT + '/authorize/' + provider.name + '?ticket=' + ticket, claimToken, flowId: flow.id });
      } else if (route.startsWith('authorize/') && req.method === 'GET') {
        const provider = providers.get(route.slice('authorize/'.length));
        const flow = live(tickets.get(digest(url.searchParams.get('ticket') || '')));
        if (provider?.name !== flow.provider) throw expired();
        tickets.delete(flow.ticketHash);
        const binding = opaque();
        flow.cookieHash = digest(binding);
        const params = new URLSearchParams({ client_id: provider.id, redirect_uri: callback(provider.name),
          state: flow.state, response_type: 'code' });
        if (provider.name === 'google') params.set('scope', 'openid');
        if (provider.name === 'apple') params.set('response_mode', 'form_post');
        if (provider.keySet) params.set('nonce', flow.nonce);
        if (provider.pkce) {
          params.set('code_challenge_method', 'S256');
          params.set('code_challenge', digest(flow.verifier));
        }
        res.writeHead(302, { Location: provider.authorize + '?' + params, 'Set-Cookie': cookie(flow, binding, LIFETIME / 1000) });
        res.end();
      } else if (route.startsWith('callback/') && (req.method === 'GET' || req.method === 'POST')) {
        const provider = providers.get(route.slice('callback/'.length));
        if (!provider || (req.method === 'POST' && provider.name !== 'apple')) throw expired();
        const params = req.method === 'POST' ? await parseBody(req, true) : url.searchParams;
        const flow = live(states.get(params.get('state')));
        const name = cookieName(flow) + '=';
        const binding = String(req.headers.cookie || '').split(';').map(value => value.trim()).find(value => value.startsWith(name))?.slice(name.length);
        if (provider.name !== flow.provider || !binding || !same(flow.cookieHash, digest(binding))) throw expired();
        states.delete(flow.state); // A second callback can never start another token exchange.
        res.setHeader('Set-Cookie', cookie(flow, '', 0));
        const code = params.get('code');
        if (params.has('error') || !code || code.length > 8192) {
          flow.status = 'denied';
          browserResult(res, false);
        } else {
          try {
            const subject = await verifiedSubject(provider, flow, code, callback(provider.name), fetchImpl);
            live(claims.get(flow.claimHash));
            const confirmationCode = String(randomInt(1_000_000)).padStart(6, '0');
            flow.receiptHash = digest(confirmationCode);
            flow.subject = subject;
            flow.status = 'verified';
            browserResult(res, true, { flowId: flow.id, confirmationCode });
          } catch {
            flow.status = 'failed';
            browserResult(res, false);
          }
        }
      } else if (route === 'claim' && req.method === 'POST') {
        const body = await parseBody(req);
        if (typeof body.claimToken !== 'string' || body.claimToken.length !== 43) throw expired();
        const flow = live(claims.get(digest(body.claimToken)));
        if (flow.status === 'failed' || flow.status === 'denied') {
          discard(flow);
          throw flow.status === 'denied' ? new AuthError(400, 'AUTH_DENIED') : upstreamFailed();
        }
        if (flow.status !== 'verified') json(res, 200, { pending: true });
        else if (!body.confirmationCode) json(res, 200, { pending: true, confirmationRequired: true });
        else {
          const supplied = body.confirmationCode;
          if (typeof supplied !== 'string' || !/^\d{6}$/.test(supplied) || !same(flow.receiptHash, digest(supplied))) {
            flow.attempts++;
            if (flow.attempts >= 5) { discard(flow); throw expired(); }
            throw new AuthError(400, 'CONFIRMATION_CODE_INVALID');
          }
          const identity = { provider: flow.provider, subject: flow.subject, nickname: flow.nickname, accountToken: flow.accountToken };
          discard(flow); // Synchronous one-time handoff before returning a durable store credential.
          let result;
          try { result = store.loginWithSocialIdentity(identity); }
          catch (error) {
            if (!identity.nickname || !['INVALID_NICKNAME','NICKNAME_TAKEN'].includes(error.code)) throw error;
            result = store.loginWithSocialIdentity({ ...identity, nickname: '' });
          }
          json(res, 200, result);
        }
      } else json(res, 404, { error: 'NOT_FOUND' });
    } catch (error) {
      const known = Number.isInteger(error.status) && error.status >= 400 && error.status < 600 && typeof error.code === 'string';
      json(res, known ? error.status : 500, { error: known ? error.code : 'AUTH_SERVER_ERROR' });
    }
    return true;
  };
}
